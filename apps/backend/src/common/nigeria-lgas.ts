export function normalizeLocationText(value: string): string {
  return value
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\s-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function areasForState(state: string): string[] {
  const lgas = NIGERIA_STATE_LGAS[state];
  if (!lgas) return [];
  const popular = (POPULAR_AREA_ALIASES[state] || []).map((item) => item.area);
  const seen = new Set<string>();
  const out: string[] = [];
  for (const item of [...popular, ...lgas]) {
    const key = item.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(item);
  }
  return out;
}

export function resolvePopularAreaToLga(state: string, area: string): string | null {
  const aliases = POPULAR_AREA_ALIASES[state] || [];
  const hit = aliases.find((item) => normalizeLocationText(item.area) === normalizeLocationText(area));
  return hit ? hit.lga : null;
}

export function isValidStateLga(state: string, lga: string): boolean {
  const list = NIGERIA_STATE_LGAS[state];
  if (!list) return false;
  const n = normalizeLocationText(lga);
  if (list.some((item) => normalizeLocationText(item) === n)) return true;
  return Boolean(resolvePopularAreaToLga(state, lga));
}

export function composeLocationLabel(lga: string, state: string): string {
  return `${lga}, ${state}`;
}

/** Best-effort parse free-text location into state + LGA labels. */
export function parseLocationToStateLga(raw?: string | null): { stateLabel: string | null; lgaLabel: string | null } {
  const text = String(raw || "").trim();
  if (!text) return { stateLabel: null, lgaLabel: null };
  const normalized = normalizeLocationText(text);
  let stateLabel: string | null = null;
  for (const state of Object.keys(NIGERIA_STATE_LGAS)) {
    const sn = normalizeLocationText(state);
    if (normalized === sn || normalized.includes(sn) || (state === "FCT" && (normalized.includes("abuja") || normalized.includes("federal capital")))) {
      stateLabel = state;
      break;
    }
  }
  if (!stateLabel) {
    // try LGA-only match across states (unique hits only)
    const hits: Array<{ state: string; lga: string }> = [];
    for (const [state, lgas] of Object.entries(NIGERIA_STATE_LGAS)) {
      for (const lga of lgas) {
        const ln = normalizeLocationText(lga);
        if (normalized === ln || normalized.includes(ln)) hits.push({ state, lga });
      }
    }
    if (hits.length === 1) return { stateLabel: hits[0].state, lgaLabel: hits[0].lga };
    return { stateLabel: null, lgaLabel: null };
  }
  const lgas = NIGERIA_STATE_LGAS[stateLabel] || [];
  for (const lga of lgas) {
    const ln = normalizeLocationText(lga);
    if (normalized.includes(ln)) return { stateLabel, lgaLabel: lga };
  }
  for (const alias of POPULAR_AREA_ALIASES[stateLabel] || []) {
    if (normalized.includes(normalizeLocationText(alias.area))) {
      return { stateLabel, lgaLabel: alias.lga };
    }
  }
  return { stateLabel, lgaLabel: null };
}
